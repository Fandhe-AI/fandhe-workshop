//! SHA-256（FIPS 180-4）。外部依存を足さないための小さな実装。
//!
//! 出所は試作（`prototype/engine/crates/core/src/sha256.rs`）で、戻り値をバイト列にし、`content_hash` の
//! 計算だけに使う。contract の外部依存は `serde`・`serde_json` に固定している（`docs/architecture.md` §3）ため、
//! `sha2` は採らない。用途は版の同一性の判定で、改ざんの検知（認証）ではない。
//! 既知解（FIPS 180-4 の例とパディングの境界）で照合する試験を、下の `tests` に置く。

